import fs from 'node:fs';
const base = 'packages/management-contracts/';
const catalog = JSON.parse(fs.readFileSync(base+'catalog.json'));
const load = path => JSON.parse(fs.readFileSync(base+path));
const name = key => key.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => c?.toUpperCase() ?? '').replace(/^./,c=>c.toUpperCase());
function ts(s) {
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(x=>JSON.stringify(x)).join(' | ');
  if (s.anyOf) return s.anyOf.map(ts).join(' | ');
  if (Array.isArray(s.type)) return s.type.map(t=>ts({type:t})).join(' | ');
  if (s.type==='array') return 'Array<'+ts(s.items)+'>';
  if (s.type==='object') {
    if (!s.properties || !Object.keys(s.properties).length) return 'Record<string, never>';
    const props=Object.entries(s.properties).filter(([k])=>!s.allOf || !['command_type','params'].includes(k));
    const record='{\n'+props.map(([k,v])=>'  '+k+(s.required?.includes(k)?'':'?')+': '+ts(v)+';').join('\n')+'\n}';
    if (!s.allOf) return record;
    return record+' & ('+s.allOf.map(rule=>'{ command_type: '+ts(rule.if.properties.command_type)+'; params: '+ts(rule.then.properties.params)+' }').join(' | ')+')';
  }
  return s.type==='integer'?'number':s.type;
}
function go(s) {
  if (s.enum || typeof s.const==='string') return 'string';
  if (s.anyOf || Array.isArray(s.type)) return 'json.RawMessage';
  if (s.type==='array') return '[]'+go(s.items);
  if (s.type==='object') {
    if (!s.properties) return 'json.RawMessage';
    return 'struct {\n'+Object.entries(s.properties).map(([k,v])=>name(k)+' '+(!s.required?.includes(k)?'*':'')+go(v)+' `json:"'+k+(s.required?.includes(k)?'':',omitempty')+'"`').join('\n')+'\n}';
  }
  return ({string:'string',integer:'int64',number:'float64',boolean:'bool'})[s.type];
}
let types='// Generated from O0 schemas by pnpm generate.\n';
let structs='// Code generated by pnpm generate. DO NOT EDIT.\npackage contracts\n\nimport "encoding/json"\n';
for (const entry of catalog) {
  const s=load(entry.schema), id=name(entry.id);
  types+='export type '+id+' = '+ts(s)+';\n';
  structs+='\ntype '+id+' '+go(s)+'\n';
  for(const rule of s.properties.body.allOf??[]) structs+='\ntype '+name(rule.if.properties.command_type.const.toLowerCase())+'Params '+go(rule.then.properties.params)+'\n';
}
types+='export type Envelope = '+catalog.map(e=>name(e.id)).join(' | ')+';\nexport interface LocalPayloads {\n';
for(const [k,s] of Object.entries(load('schemas/LOCAL-01.product-management.schema.json').$defs)) {
  types+='  '+k+': '+ts(s)+';\n'; structs+='\ntype '+name(k)+' '+go(s)+'\n';
}
fs.mkdirSync(base+'generated',{recursive:true});
fs.writeFileSync(base+'generated/types.ts',types+'}\n');
fs.writeFileSync(base+'types_generated.go',structs);
